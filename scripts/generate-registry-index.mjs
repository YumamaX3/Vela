#!/usr/bin/env node
/**
 * generate-registry-index.mjs — the registry index emitter (M3, board B7).
 *
 * WHY THIS EXISTS: the two scripts that once maintained open-sse/providers/registry/index.js
 * (migrate-registry.mjs, injectDisplayToRegistry.mjs) were untracked at fafcaf5a and later
 * lost from disk; migrate-registry only migrated per-file schema anyway — NEITHER emitted
 * the index. The index drifted: 14 committed provider files sat unimported (the
 * 2026-09-04 debt, now sealed). This script is the missing emitter, written fresh.
 *
 * WHAT IT DOES: scans open-sse/providers/registry/*.js (LC_ALL=C byte order, the order
 * the old index kept), and writes index.js: one `import pN from "./<slug>.js";` per
 * provider, then `export default [ ...pN ];` in the same order. Deterministic — same
 * directory, same bytes.
 *
 * HIDDEN: providers deliberately kept out of the runtime index. Their files stay on
 * disk (the census suite, tests/unit/provider-registry-census.test.js, enforces both
 * halves). This list and the suite's HIDDEN set must agree — the suite fails if a
 * hidden name is imported, or if a hidden file vanishes from disk.
 *
 * RUN: node scripts/generate-registry-index.mjs [--dry]
 */
import { readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const REGISTRY_DIR = join(here, "..", "open-sse", "providers", "registry");
const OUT = join(REGISTRY_DIR, "index.js");
const DRY = process.argv.includes("--dry");

// Keep in lockstep with HIDDEN in tests/unit/provider-registry-census.test.js.
const HIDDEN = new Set(["trae", "devin-cli", "windsurf"]);
const HIDDEN_NOTE =
  "// Temporarily hidden — no tool calling support (trae SOLO agent / windsurf gRPC skip ToolCallChunk)." +
  "\n// Files stay on disk; re-enable by removing the name from HIDDEN in this script and" +
  "\n// tests/unit/provider-registry-census.test.js, then re-running the emitter.";

const slugs = readdirSync(REGISTRY_DIR)
  .filter((f) => f.endsWith(".js") && f !== "index.js")
  .map((f) => f.replace(/\.js$/, ""))
  .sort((a, b) => (a < b ? -1 : a > b ? 1 : 0)); // LC_ALL=C byte order

const visible = slugs.filter((s) => !HIDDEN.has(s));
const hiddenPresent = slugs.filter((s) => HIDDEN.has(s));

const lines = [];
lines.push("// GENERATED by scripts/generate-registry-index.mjs — do not hand-edit.");
lines.push(`// Census: ${visible.length} imported providers (+ ${hiddenPresent.length} hidden: ${hiddenPresent.join(", ")}).`);
lines.push("// Stream handler with disconnect detection - shared for all providers");
visible.forEach((slug, i) => lines.push(`import p${i} from "./${slug}.js";`));
if (hiddenPresent.length) {
  lines.push(HIDDEN_NOTE);
  for (const slug of hiddenPresent) lines.push(`// hidden (not imported): ./${slug}.js`);
}
lines.push("");
lines.push("export default [");
visible.forEach((slug, i) => lines.push(`  p${i},`));
if (hiddenPresent.length) {
  for (const slug of hiddenPresent) lines.push(`  // hidden: ${slug}`);
}
lines.push("];");
lines.push("");

const output = lines.join("\n");

if (DRY) {
  console.log(`[DRY] would write ${OUT}`);
  console.log(`[DRY] ${visible.length} imported, ${hiddenPresent.length} hidden`);
  console.log(`[DRY] first: ${visible[0]} · last: ${visible[visible.length - 1]}`);
  console.log(output.split("\n").slice(0, 8).join("\n"));
  console.log("  ...");
} else {
  writeFileSync(OUT, output, "utf8");
  console.log(`✅ wrote ${OUT}: ${visible.length} imported providers, ${hiddenPresent.length} hidden`);
}
